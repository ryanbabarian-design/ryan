-- Exact production helper, copied from read-only pg_get_functiondef inspection.
CREATE FUNCTION pg_temp.v235_assignment_scope_matches(
  p_step_order integer, p_assignment_department text, p_proposal_department text
) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN p_step_order IN (2,3) THEN
      nullif(btrim(coalesce(p_assignment_department,'')), '') =
      nullif(btrim(coalesce(p_proposal_department,'')), '')
    WHEN p_step_order = 4 THEN nullif(btrim(coalesce(p_assignment_department,'')), '') IS NULL
    ELSE false
  END;
$$;

CREATE FUNCTION pg_temp.ceo_test_assert(p_ok boolean, p_label text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF p_ok IS NOT TRUE THEN RAISE EXCEPTION 'FAIL: %', p_label; END IF;
  INSERT INTO pg_temp.ceo_reminder_test_results VALUES (p_label);
END;
$$;

