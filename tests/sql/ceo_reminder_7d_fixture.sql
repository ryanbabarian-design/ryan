CREATE FUNCTION pg_temp.ceo_test_proposal(
  p_number integer, p_age interval DEFAULT interval '7 days',
  p_department text DEFAULT '연구', p_submission text DEFAULT '상신완료'
) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE
  v_id uuid := ('00000000-0000-0000-0000-' || lpad(p_number::text,12,'0'))::uuid;
BEGIN
  INSERT INTO pg_temp.proposals VALUES
    (v_id,'TEST-' || p_number,'격리 테스트 ' || p_number,p_department,'테스트 제안자',true,p_submission);
  INSERT INTO pg_temp.approval_records(proposal_id,step_id,status,actionable_at)
    VALUES (v_id,1,'승인',NULL), (v_id,2,'승인',NULL), (v_id,3,'승인',NULL),
      (v_id,4,'대기',now() - p_age);
  RETURN v_id;
END;
$$;
